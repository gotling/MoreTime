"""Generate the web app icons in lib/Web/Icons.h.

Run from the project root: python3 tools/make_icons.py (needs Pillow).
"""

import io
import math

from PIL import Image, ImageDraw

BACKGROUND = (22, 24, 29)
ACCENT = (255, 122, 61)
SIZES = [192, 512]
# Draw larger and scale down for smooth edges
SUPERSAMPLE = 4


def draw_icon(size):
    big = size * SUPERSAMPLE
    image = Image.new("RGB", (big, big), BACKGROUND)
    draw = ImageDraw.Draw(image)
    center = big / 2

    # Keep everything inside the central 80 % so Android can mask it to any shape
    ring = big * 0.28
    dot = big * 0.035
    for hour in range(12):
        angle = math.radians(hour * 30)
        x = center + ring * math.sin(angle)
        y = center - ring * math.cos(angle)
        r = dot * (1.4 if hour % 3 == 0 else 1)
        draw.ellipse((x - r, y - r, x + r, y + r), fill=ACCENT)

    width = round(big * 0.045)
    hands = [(0, big * 0.17), (120, big * 0.12)]  # Minute hand at 12, hour hand at 4
    for degrees, length in hands:
        angle = math.radians(degrees)
        end = (center + length * math.sin(angle), center - length * math.cos(angle))
        draw.line((center, center, *end), fill=ACCENT, width=width)
        draw.ellipse((end[0] - width / 2, end[1] - width / 2, end[0] + width / 2, end[1] + width / 2), fill=ACCENT)
    hub = width * 0.9
    draw.ellipse((center - hub, center - hub, center + hub, center + hub), fill=ACCENT)

    return image.resize((size, size), Image.LANCZOS)


def png_bytes(image):
    buffer = io.BytesIO()
    # Two colours plus their blends along the edges, a small palette keeps the file small
    image.quantize(colors=16).save(buffer, "PNG", optimize=True)
    return buffer.getvalue()


def c_array(name, data):
    lines = [f"static const uint8_t {name}[] PROGMEM = {{"]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    parts = [
        "#ifndef _ICONS_H_",
        "#define _ICONS_H_",
        "",
        "#include <pgmspace.h>",
        "#include <stdint.h>",
        "",
        "// Web app icons, generated by tools/make_icons.py. Do not edit by hand.",
        "",
    ]
    for size in SIZES:
        data = png_bytes(draw_icon(size))
        print(f"icon{size}.png: {len(data)} bytes")
        parts.append(c_array(f"ICON_{size}", data))
        parts.append("")
    parts.append("#endif")

    with open("lib/Web/Icons.h", "w") as file:
        file.write("\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
